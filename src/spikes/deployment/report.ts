import type { ArmAssessment, ProbeResult, SpikeResult } from "./types.ts"

/**
 * The security probes measure the runtime's own capability boundary. They say
 * nothing about whether an OS sandbox holds, which is a separate deployment
 * finding (`DEP-1` / `DG-3`).
 */
export const SECURITY_SCOPE =
  "Covers inner runtime capability denial only; OS-sandbox enforcement remains DEP-1/DG-3."

export const DEPLOYMENT_SCOPE =
  "This envelope covers pure-user-space probes; DG-3 option E is the response."

const cell = (value: string): string => value.replaceAll("|", "\\|").replaceAll("\n", " ")

const table = (
  headers: ReadonlyArray<string>,
  rows: ReadonlyArray<ReadonlyArray<string>>,
): string =>
  [
    `| ${headers.map(cell).join(" | ")} |`,
    `|${headers.map(() => "---").join("|")}|`,
    ...rows.map((row) => `| ${row.map(cell).join(" | ")} |`),
  ].join("\n")

const count = (probes: ReadonlyArray<ProbeResult>, status: string): number =>
  probes.filter((probe) => probe.status === status).length

const COVERAGE: ReadonlyArray<readonly [string, ReadonlyArray<string>]> = [
  ["user namespaces", ["NS-01", "NS-02", "NS-03", "NS-04", "NS-05", "NS-06"]],
  ["same-UID process visibility and /proc", ["PR-01", "PR-02", "PR-05"]],
  ["ptrace and Yama", ["PR-02", "PR-03", "PR-06"]],
  ["secret reachability", ["PR-05", "SC-01", "SC-02", "SC-03", "SC-04", "SC-05"]],
  ["Landlock", ["LL-01", "LL-02", "LL-03", "LL-04"]],
  ["systemd user manager and hardening", ["SD-01", "SD-02", "SD-03", "SD-04", "SD-09"]],
  ["PrivateTmp", ["SD-05"]],
  ["PrivateNetwork", ["SD-06"]],
  ["RestrictAddressFamilies", ["SD-07"]],
  ["memory, CPU, and pid limits", ["LM-01", "LM-02", "LM-03", "LM-04", "LM-05"]],
  ["systemd limits under same-UID control", ["SD-10"]],
  ["restart, linger, orphan, crash recovery", [
    "RC-01",
    "RC-02",
    "RC-03",
    "RC-04",
    "RC-05",
    "RC-06",
  ]],
  ["loopback binding and ingress exposure", ["NW-01", "NW-02", "NW-03"]],
  ["broker identity", ["BI-01", "BI-02", "BI-03", "BI-04"]],
  ["fail-closed behaviour", ["FC-01", "FC-02", "SD-09", "RC-04"]],
]

const byCategory = (
  probes: ReadonlyArray<ProbeResult>,
  categories: ReadonlyArray<string>,
): ReadonlyArray<ProbeResult> => {
  const wanted = new Set(categories)
  return probes.filter((probe) => wanted.has(probe.category))
}

const armSection = (arm: ArmAssessment): ReadonlyArray<string> => [
  `### ${arm.arm}`,
  "",
  `- Secret isolation: **${arm.secretIsolation}** (${arm.note})`,
  `- Kernel-enforced, measured: ${
    arm.kernelEnforced.length === 0 ? "none" : arm.kernelEnforced.join(", ")
  }`,
  `- Conventional or measured-violating: ${
    arm.conventional.length === 0 ? "none" : arm.conventional.join(", ")
  }`,
  `- Kernel claims left unverified: ${
    arm.unverified.length === 0 ? "none" : arm.unverified.join(", ")
  }`,
  "",
]

const probeRows = (probes: ReadonlyArray<ProbeResult>): ReadonlyArray<ReadonlyArray<string>> =>
  probes.map((probe) => [probe.id, probe.category, probe.status, probe.observed])

export const renderReport = (result: SpikeResult): string => {
  const { host, probes, arms, recommendation, decisionGate, envelope } = result
  const failures = probes.filter((probe) => probe.status === "fail")
  const blocked = probes.filter((probe) => probe.status === "blocked")
  const inconclusive = probes.filter((probe) => probe.status === "inconclusive")
  const sameUid = byCategory(probes, ["same-uid-process", "secret-reachability", "broker-identity"])

  return [
    "# S2 / DEP-1 — Host-security enforcement matrix",
    "",
    `Protocol \`S2\` (\`DEP-1\`), dataset \`security-v1\`. Generated by \`src/spikes/deployment/main.ts\`;`,
    "the machine-readable result is `spikes/deployment/result.json`.",
    "",
    "Every row is a measurement on this host. `blocked` means the capability could not be exercised",
    "from this unprivileged run and is never converted into a pass.",
    "",
    "## Host",
    "",
    `- host: \`${host.hostname}\` (${host.kernel})`,
    `- deployment identity: \`${host.user}\` uid=${host.uid} groups=[${host.groups.join(" ")}]`,
    `- systemd: ${host.systemd}; cgroup ${host.cgroupVersion}; delegated controllers=[${
      host.delegatedControllers.join(" ")
    }]`,
    `- kernel.yama.ptrace_scope=${host.yamaPtraceScope}; user.max_user_namespaces=${host.maxUserNamespaces}; Landlock ABI=${host.landlockAbi}`,
    `- linger=${host.linger}; effective capabilities=${host.ambientCapabilities}`,
    "",
    "## Summary",
    "",
    `- probes: ${probes.length} (pass ${count(probes, "pass")}, fail ${
      count(probes, "fail")
    }, blocked ${count(probes, "blocked")}, inconclusive ${count(probes, "inconclusive")})`,
    `- measured failures: ${
      failures.length === 0 ? "none" : failures.map((probe) => probe.id).join(", ")
    }`,
    `- unavailable (blocked): ${
      blocked.length === 0 ? "none" : blocked.map((probe) => probe.id).join(", ")
    }`,
    `- inconclusive: ${
      inconclusive.length === 0 ? "none" : inconclusive.map((probe) => probe.id).join(", ")
    }`,
    "",
    "## Coverage",
    "",
    table(["required area", "probes"], COVERAGE.map(([area, ids]) => [area, ids.join(", ")])),
    "",
    "## Method notes",
    "",
    "- Kernel facilities Deno cannot call directly (Landlock) run in a child process through `libc` syscalls; the child reports through `write(2)` after `landlock_restrict_self`, so the runtime's descriptor bookkeeping cannot mask the result.",
    "- `PTRACE_ATTACH` is measured with `strace -p` from a sibling, controlled with `strace -f` on an own child, and corroborated by `/proc/<pid>/mem` so one tool quirk cannot decide the finding.",
    "- `SO_PEERCRED` is read by a Perl server against an `nc -U` client: Deno exposes no peer-credentials API and its FFI socket path crashes this runtime.",
    "- Hardening directives are measured twice: effective unit properties, and behaviour inside the unit. A directive counts only when the behaviour changes.",
    "- The modelled same-UID attacker runs with Deno permissions disabled. Deno's permission flags are an inner boundary, not an OS boundary, so granting them would understate hostile same-UID code.",
    "- Every systemd probe uses transient `--user` units and removes them; no unit file, package, or host setting is modified.",
    "",
    "## Enforcement matrix",
    "",
    table(["probe", "category", "status", "observation"], probeRows(probes)),
    "",
    "## Same-UID findings",
    "",
    "The decisive question for `DEP-1` is what another process of the same UID can do to the broker.",
    "",
    table(["probe", "category", "status", "observation"], probeRows(sameUid)),
    "",
    "Interpretation, limited to what was measured:",
    "",
    "1. Process metadata (`cmdline`, `environ`, `maps`, `cgroup`) of a same-UID sibling is readable; a canary placed in the environment was visible (PR-01).",
    "2. Memory inspection is denied by Yama (`/proc/<pid>/mem`, `PTRACE_ATTACH` on a sibling), while tracing an own child still works (PR-02, PR-03). Denial is ancestry-based and depends on `kernel.yama.ptrace_scope >= 1`.",
    "3. Signals are delivered to a same-UID sibling, so broker and core liveness is not protected (PR-04).",
    "4. A credential file held open by the modelled broker was read through `/proc/<pid>/fd/<n>` by a same-UID sibling (PR-05). This is the strongest single finding: pure user-space cannot protect broker secrets, even with Yama enabled.",
    "5. A 0600 file in a 0700 directory is readable by the same UID (SC-01); a 0444 audit file can be truncated and unlinked by its owner's UID (SC-03).",
    "6. Unix socket credentials report only pid/uid/gid; a same-UID client is indistinguishable from the frozen core (BI-01).",
    "7. Supplementary group `docker` plus `/var/run/docker.sock` is root-equivalent on this host (SC-04).",
    "",
    "## Evidence envelope",
    "",
    `- test: \`${envelope.testId}\``,
    `- fixture: \`${envelope.fixtureVersion}\``,
    `- outcome: \`${envelope.outcome}\``,
    `- covered invariants: ${envelope.invariantIds.join(", ")}`,
    `- scope: ${SECURITY_SCOPE}`,
    `- ${DEPLOYMENT_SCOPE}`,
    "",
    "## Fail-closed evidence",
    "",
    table(
      ["probe", "category", "status", "observation"],
      probeRows(byCategory(probes, ["fail-closed"])),
    ),
    "",
    "- An audit sink that cannot be written denies the guarded effect; the effect did not run and the denial was recorded (FC-02).",
    "- An interrupted non-idempotent effect is classified `outcome_unknown`, never success (RC-04).",
    "- systemd rejects unknown properties and invalid values instead of degrading (SD-09).",
    "- A valid directive can still be ineffective: `ProtectSystem=strict` with `ReadWritePaths=<state>` left the state path read-only (SD-04). The write fails closed, but a deployment that depends on the directive would not start; startup verification of effective values is required.",
    "",
    "## Deployment plane comparison",
    "",
    "| variant | process identities | measured consequences on this host |",
    "|---|---|---|",
    "| A. home-manager user unit | all components under the deployment user | broker secrets readable through `/proc/<pid>/fd` and 0600 files; ceilings rewritable by the same UID; watchdog, restart, and unit control are conventional (PR-05, SC-01, SD-10, RC-01) |",
    "| B. NixOS-plane user unit | same single UID | same exposures as A; system rebuild may restart units, but identity separation is unchanged |",
    "| C. dedicated system units | trusted components as dedicated users | intended kernel-enforced separation; **unverified here** because no privileged operation was permitted (BI-03) |",
    "| D. hybrid user core + dedicated broker/sandbox helper | core/agents/UI under the user, broker and supervisor as system users | keeps the user-controlled mutable layer while removing the measured secret-isolation failures from the broker's UID boundary |",
    "",
    ...arms.flatMap(armSection),
    "## Broker identity recommendation",
    "",
    `**Variant ${recommendation.variant}.** ${recommendation.summary}`,
    "",
    "Rationale:",
    "",
    ...recommendation.rationale.map((line) => `- ${line}`),
    "",
    "Required conditions:",
    "",
    ...recommendation.requiredConditions.map((line) => `- ${line}`),
    "",
    "Rejected alternatives:",
    "",
    ...recommendation.rejectedAlternatives.map((line) => `- ${line}`),
    "",
    "## Residuals",
    "",
    ...result.residuals.map((line) => `- ${line}`),
    "",
    "## Unavailable capabilities",
    "",
    result.blockedCapabilities.length === 0
      ? "- none"
      : result.blockedCapabilities.map((line) => `- ${line}`).join("\n"),
    "",
    "## Impact on DG-3",
    "",
    `- gate: \`${decisionGate.gate}\` — status: \`${decisionGate.status}\``,
    `- dependent tasks: ${decisionGate.blocks.join(", ")}`,
    `- evidence probes cited: ${
      decisionGate.evidenceProbes.length === 0 ? "none" : decisionGate.evidenceProbes.join(", ")
    }`,
    `- ${decisionGate.statement}`,
    "",
    "`DG-3` remains open. This report is the pre-registered evidence input; it does not select a",
    "deployment plane by itself, and the unverified dedicated-UID claims stay unverified until a",
    "privileged run or a human-reviewed host configuration record supplies them.",
    "",
    "## Reproduction",
    "",
    "```sh",
    "deno run -A src/spikes/deployment/main.ts",
    "deno test -A tests/spikes/deployment",
    "```",
    "",
  ].join("\n")
}
